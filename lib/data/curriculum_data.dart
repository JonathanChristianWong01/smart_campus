  for (final SemesterKurikulum s in kKurikulum) ...s.mataKuliah,
];

/// Mata kuliah inti yang ditampilkan pada Beranda aplikasi.
final List<MataKuliah> kMataKuliahUnggulan = <MataKuliah>[
  for (final MataKuliah m in kSemuaMataKuliah) if (m.kode == '110100') m,
  for (final MataKuliah m in kSemuaMataKuliah) if (m.kode == '114100') m,
  for (final MataKuliah m in kSemuaMataKuliah) if (m.kode == '010500') m,
  for (final MataKuliah m in kSemuaMataKuliah) if (m.kode == '010600') m,
  for (final MataKuliah m in kSemuaMataKuliah) if (m.kode == '112200') m,
  for (final MataKuliah m in kSemuaMataKuliah) if (m.kode == '111000') m,
];

/// Cari mata kuliah berdasarkan kode (mis. `110100`).
MataKuliah? mataKuliahByKode(String kode) {
  for (final MataKuliah m in kSemuaMataKuliah) {
    if (m.kode == kode) return m;
  }
  return null;
}

/// Total SKS hasil penjumlahan seluruh mata kuliah pada kurikulum.
int get totalSksKurikulum =>
    kSemuaMataKuliah.fold<int>(0, (int a, MataKuliah m) => a + m.sks);
